function inside(poly: Poly, lon: number, lat: number): boolean {
  let hit = false
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i]
    const [xj, yj] = poly[j]
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit
  }
  return hit
}

let cache: Float32Array | null = null
/** Land dots as a flat [lon, lat, lon, lat, …] array (computed once). ~1.8° spacing on the sphere. */
export function landDots(): Float32Array {
  if (cache) return cache
  const out: number[] = []
  const step = 1.8
  for (let lat = -58; lat <= 84; lat += step) {
    const lonStep = step / Math.max(0.2, Math.cos((lat * Math.PI) / 180))
    for (let lon = -180; lon < 180; lon += lonStep) {
      if (LAND.some(p => inside(p, lon, lat))) out.push(lon, lat)
    }
  }
  cache = new Float32Array(out)
  return cache
}
